function primaryPosCode(posStr) {
  const raw = String(posStr || '').toLowerCase().trim();
  const first = raw.split('/')[0].trim();
  if (['v', 'vn', 'vd', 'vg'].includes(first)) return 'v';
  if (['n', 'nr', 'ns', 'nt', 'nz', 'ng'].includes(first)) return 'n';
  if (['a', 'ad', 'an', 'ag', 'b'].includes(first)) return 'a';
  if (['d', 'dg'].includes(first)) return 'd';
  if (['t', 'tg'].includes(first)) return 't';
  if (['s'].includes(first)) return 's';
  if (['l', 'i'].includes(first)) return 'l';
  if (['c'].includes(first)) return 'c';
  if (['q', 'qv'].includes(first)) return 'q';
  if (['m'].includes(first)) return 'm';
  return 'general';
}

