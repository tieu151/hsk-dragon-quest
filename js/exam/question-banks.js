export function getListeningDialoguesForLevel(level, preferredSetIndex = 0, excludeIds = new Set()) {
  const lv = Number(level) || 1;
  let pool = LISTENING_DIALOGUES.filter((d) => d.level === lv);
  if (pool.length < 16 && lv >= 7) {
    const highTier = LISTENING_DIALOGUES.filter((d) => d.level >= 7 && d.level !== lv);
    pool = [...pool, ...highTier];
  }
  return orderPoolBySetAndSeen(pool, preferredSetIndex, excludeIds);
}

export function getWritingQuestionsForLevel(level, preferredSetIndex = 0, excludeIds = new Set()) {
  const lv = Number(level) || 1;
  let pool = ALL_WRITING_QUESTIONS.filter((w) => w.level === lv);
  if (pool.length < 16 && lv >= 7) {
    const highTier = ALL_WRITING_QUESTIONS.filter((w) => w.level >= 7 && w.level !== lv);
    pool = [...pool, ...highTier];
  }
  return orderPoolBySetAndSeen(pool, preferredSetIndex, excludeIds);
}

function orderPoolBySetAndSeen(pool, preferredSetIndex = 0, excludeIds = new Set()) {
  if (preferredSetIndex >= 1 && preferredSetIndex <= 4) {
    const inSet = pool.filter((item) => item.setIndex === preferredSetIndex && !excludeIds.has(item.id));
    const nextSet = pool.filter((item) => item.setIndex !== preferredSetIndex && !excludeIds.has(item.id));
    const seen = pool.filter((item) => excludeIds.has(item.id));
    return [...inSet, ...nextSet, ...seen];
  }
  const unseen = pool.filter((item) => !excludeIds.has(item.id));
  return unseen;
}

