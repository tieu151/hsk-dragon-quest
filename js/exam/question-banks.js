export function getContextualSentenceForWord(word, seedIdx = 0) {
  if (!word || !word.hanzi) return null;
  if (word.exZh && word.exZh.includes(word.hanzi) && word.exZh.trim().length >= word.hanzi.length + 4) {
    return {
      zh: word.exZh.trim(),
      py: word.exPy || word.pinyin || '',
      vi: word.exVi || word.meaning || ''
    };
  }
  if (CURATED_SENTENCES[word.hanzi]) {
    return CURATED_SENTENCES[word.hanzi];
  }
  const lv = Number(word.level) || 1;
  const tier = lv <= 2 ? 'low' : lv <= 5 ? 'mid' : 'high';
  const posKey = primaryPosCode(word.pos);
  const tierFrames = POS_FRAMES[tier];
  const frames = tierFrames[posKey] || tierFrames.general;
  const idx = Math.abs(Number(seedIdx) || 0) % frames.length;
  const zh = frames[idx].replace(/\{W\}/g, word.hanzi);
  return {
    zh,
    py: word.pinyin || '',
    vi: `Từ trọng tâm "${word.hanzi}" (${word.pinyin}) [${word.pos}]: ${word.meaning}`
  };
}
