// Sinh câu hỏi Ngữ pháp & Biểu đạt (语法与表达) động từ kho từ vựng để không bao giờ trùng lặp
export function buildDynamicWritingGrammar(word, distractors, seedIdx = 0) {
  if (!word || !word.hanzi || !Array.isArray(distractors) || distractors.length < 3) return null;
  const ctx = getContextualSentenceForWord(word, seedIdx);
  const wrongSentences = distractors.slice(0, 3).map((d, i) => {
    if (i === 0) return `虽然今天已经很晚了，但是“${word.hanzi}”把房间打扫得非常昨天。`;
    if (i === 1) return `通过这次关于“${word.hanzi}”的讨论，使大家完全忘记了宾语和主语。`;
    return `能不能掌握好“${word.hanzi}”这个词，关键在于平时多做阅读练习的肯定。`;
  });
  return {
    id: `dyn_wg_${word.id}`,
    level: Number(word.level) || 1,
    subSkill: 'grammar',
    wordId: word.id,
    segments: null,
    stem: `【语法与语境辨析】Chọn câu sử dụng từ "${word.hanzi}" (${word.pinyin}) ĐÚNG ngữ pháp và tự nhiên nhất:`,
    options: [ctx.zh, ...wrongSentences],
    correctIndex: 0,
    explanation: `Câu đúng ngữ pháp là: "${ctx.zh}". Các câu còn lại mắc lỗi kết hợp từ, khuyết chủ ngữ (通过……使……) hoặc lỗi hai mặt đối một mặt (能不能……在于……肯定).`
  };
}

// Sinh hội thoại Nghe hiểu thực tế động từ kho từ vựng khi cần bổ sung chống lặp
export function buildDynamicListeningDialogue(word, distractors, seedIdx = 0) {
  if (!word || !word.hanzi || !Array.isArray(distractors) || distractors.length < 3) return null;
  const ctx = getContextualSentenceForWord(word, seedIdx);
  const audioText = `男：在刚才那段话里，老师重点强调了哪个词？ 女：${ctx.zh} 最关键的就是“${word.hanzi}”这个词。`;
  const question = '女的重点提到的那个词是什么意思？';
  return {
    id: `dyn_ld_${word.id}`,
    level: Number(word.level) || 1,
    wordId: word.id,
    audioText,
    question,
    options: [word.meaning, ...distractors.slice(0, 3).map((d) => d.meaning)],
    correctIndex: 0,
    explanation: `Kịch bản hội thoại: ${audioText} — Từ trọng tâm "${word.hanzi}" (${word.pinyin}) nghĩa là: "${word.meaning}".`
  };
}

